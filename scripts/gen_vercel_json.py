#!/usr/bin/env python3
"""Generate vercel.json (repo root) from docs/_headers and docs/_redirects.

Those two files are generated by scripts/restructure.py for Cloudflare Pages.
Vercel ignores them, so this script translates them. Run it again after
restructure.py changes either file:

    python3 scripts/gen_vercel_json.py

Mapping:
  _redirects  301/302/307/308 lines  ->  "redirects"   (first rule wins, same as Cloudflare)
  _redirects  200 lines              ->  "rewrites"
  _headers    /*                     ->  source /(.*)
  _headers    /*.png                 ->  source /(.*)\\.png
  _headers    https://:project.pages.dev/*  ->  host rule for *.vercel.app and new.devcon.ph only
              (noindex stays on preview/staging URLs, never on devcon.ph)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
OUT = os.path.join(ROOT, "vercel.json")
PREVIEW_HOST = r"(.+\.vercel\.app|new\.devcon\.ph)"   # preview URLs and the staging hostname; never devcon.ph or www
REDIRECT_CODES = (301, 302, 307, 308)


def parse_redirects(path):
    redirects, rewrites, seen = [], [], set()
    for raw in open(path, encoding="utf-8"):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 2:
            sys.exit(f"Bad _redirects line: {line!r}")
        source, destination = parts[0], parts[1]
        status = int(parts[2]) if len(parts) > 2 else 301
        if source in seen:
            continue  # first matching rule wins, as on Cloudflare Pages
        seen.add(source)
        if status == 200:
            rewrites.append({"source": source, "destination": destination})
        elif status in REDIRECT_CODES:
            redirects.append({"source": source, "destination": destination, "statusCode": status})
        else:
            sys.exit(f"Unsupported status in _redirects: {line!r}")
    return redirects, rewrites


def parse_headers(path):
    blocks, current = [], None
    for raw in open(path, encoding="utf-8"):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw.startswith((" ", "\t")):
            current = {"pattern": raw.strip(), "headers": []}
            blocks.append(current)
        else:
            key, _, value = raw.strip().partition(":")
            current["headers"].append({"key": key.strip(), "value": value.strip()})
    return blocks


def translate_headers(blocks):
    rules = []
    for block in blocks:
        pattern = block["pattern"]
        rule = {"headers": block["headers"]}
        if pattern.startswith("https://") and "pages.dev" in pattern:
            rule["source"] = "/(.*)"
            rule["has"] = [{"type": "host", "value": PREVIEW_HOST}]
        elif pattern == "/*":
            rule["source"] = "/(.*)"
        elif pattern.startswith("/*."):
            rule["source"] = "/(.*)\\." + pattern[3:]
        elif re.fullmatch(r"/[A-Za-z0-9._/-]+", pattern):
            rule["source"] = pattern
        else:
            sys.exit(f"Unsupported _headers pattern: {pattern!r}")
        # keep source first for readability
        rules.append({"source": rule.pop("source"), **rule})
    return rules


def main():
    redirects, rewrites = parse_redirects(os.path.join(DOCS, "_redirects"))
    headers = translate_headers(parse_headers(os.path.join(DOCS, "_headers")))
    config = {
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "framework": None,
        "installCommand": None,
        "buildCommand": None,
        "outputDirectory": "docs",
        "trailingSlash": True,
        "headers": headers,
        "redirects": redirects,
        "rewrites": rewrites,
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(config, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"vercel.json: {len(headers)} header rules, {len(redirects)} redirects, {len(rewrites)} rewrites")


if __name__ == "__main__":
    main()
